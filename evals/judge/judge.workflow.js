export const meta = {
  name: 'deck-judge',
  description: 'Blind rubric judging of A/B decks per case, plus the generated-vs-real discrimination test',
  phases: [{ title: 'Rubric', detail: 'one judge per case, blind A/B' }, { title: 'Discriminate', detail: '3 independent judges' }],
}
// args: { casesDir, pairDir, cases: [..], rubric, calibration, discDir, discItems: [..] }
const DIMS = ['storyline', 'synthesis', 'framework_fit', 'page_grammar', 'data_integrity', 'visual_quality', 'decision_readiness']
const scoreObj = { type: 'object', properties: Object.fromEntries(DIMS.map(d => [d, { type: 'integer', minimum: 1, maximum: 5 }])), required: DIMS }
const RUBRIC_OUT = {
  type: 'object',
  properties: { A: scoreObj, B: scoreObj, A_weakest: { type: 'string' }, B_weakest: { type: 'string' }, preferred: { enum: ['A', 'B', 'tie'] } },
  required: ['A', 'B', 'A_weakest', 'B_weakest', 'preferred'],
}
const DISC_OUT = {
  type: 'object',
  properties: { calls: { type: 'array', items: { type: 'object', properties: { item: { type: 'string' }, call: { enum: ['generated', 'real'] }, confidence: { type: 'integer', minimum: 1, maximum: 5 }, reason: { type: 'string' } }, required: ['item', 'call', 'confidence', 'reason'] } } },
  required: ['calls'],
}

phase('Rubric')
const rubric = parallel(args.cases.map(c => () => agent(
  `You are a blind judge of two decks built for the same brief. Read the rubric at ${args.rubric} and the calibration anchors at ${args.calibration} (an expert's 1–5 grades of ten slides with the reasons — match their standard: kit-style clean single-message pages ≈ 4; dense per-unit scatter plots ≈ 2; text-heavy summaries ≈ 3).
The brief is the "prompt" in ${args.casesDir}/${c}/case.yaml. The inputs the deck builder had are in ${args.casesDir}/${c}/input/ (you may read them to check numbers).
Deck A: contact sheets ${args.pairDir}/${c}/A/*-grid-*.jpg (full PDF: ${args.pairDir}/${c}/A/deck.pdf).
Deck B: contact sheets ${args.pairDir}/${c}/B/*-grid-*.jpg (full PDF: ${args.pairDir}/${c}/B/deck.pdf).
Read every contact sheet of both decks. Render any page larger with pdftoppm if you need to read small text. Do not read anything else under evals/runs or ~/deck-corpus, and do not try to learn which tool built which deck.
Score each deck 1–5 on every rubric dimension, name its weakest slide in ≤30 words, and state which deck a partner would rather send. Be strict and independent: the same score for both is fine if deserved.`,
  { label: `judge ${c}`, phase: 'Rubric', schema: RUBRIC_OUT }).then(r => ({ case: c, ...r }))))

phase('Discriminate')
const disc = parallel([1, 2, 3].map(j => () => agent(
  `Blind test. ${args.discItems.length} slide images are in ${args.discDir} (${args.discItems.join(', ')}.jpg). Some are real slides from professional consulting and banking decks; some were generated by an AI deck tool. Thin bands at the top and bottom of every slide were painted out on purpose, on both kinds. Aspect ratio, white padding, logos, firm or client names, subject matter, and whether a company is fictional are NOT evidence — ignore them. Judge only page grammar and storyline cues: title construction, chart choice and labelling, annotation, density, alignment, footnotes, consistency.
For every item answer "generated" or "real", a confidence 1–5, and a one-line reason naming the cue you used.`,
  { label: `discriminator ${j}`, phase: 'Discriminate', schema: DISC_OUT })))

const [rubricResults, discResults] = await Promise.all([rubric, disc])
return { rubric: rubricResults.filter(Boolean), discrimination: discResults.filter(Boolean) }
